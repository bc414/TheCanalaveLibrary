namespace TheCanalaveLibrary.Core;

/// <summary>
/// One vote: a user's pick of one poll option. A multi-select vote is one row per picked option.
/// <para><b>Keyed by a surrogate <see cref="PollVoteId"/></b> (owner ruling D13, WU-UserDeletion
/// 2026-10-13). <see cref="UserId"/> is nullable: a deleted account's votes survive anonymized
/// (<c>ON DELETE SET NULL</c>), because a poll is a point-in-time record and cascading its votes
/// rewrote the published result. One live vote per (option, user) is enforced by the unique index
/// <c>ix_poll_votes_poll_option_id_user_id</c>, which keeps Postgres's default NULLS DISTINCT so any
/// number of anonymized rows can share an option (<c>layer1-data-model.md</c> §"Column
/// Conventions").</para>
/// <para><b>Single-choice is a database constraint</b> (owner ruling D23, WU-PollVoteIntegrity
/// 2026-10-13): one live vote per voter on a poll with <c>AllowMultiple = false</c>. The row carries
/// <see cref="PollId"/> (kept honest by the composite FK <c>(poll_id, poll_option_id)</c> →
/// <c>poll_options</c>) and the poll's <see cref="AllowMultiple"/> (kept honest by the composite FK
/// <c>(poll_id, allow_multiple)</c> → <c>base_polls</c>, which has no ON UPDATE action, so the poll's
/// mode cannot change while any vote references it). <see cref="SingleChoicePollId"/> is generated
/// from the two and unique with <see cref="UserId"/>. No writer can break the rule, and none has to
/// remember it (<c>layer2-services.md</c> §"Check-then-act posture").</para>
/// </summary>
public class PollVote
{
    public int PollVoteId { get; set; }

    /// <summary>The voted poll. Equal to the option's <c>PollOption.PollId</c> by the composite FK.</summary>
    public int PollId { get; set; }

    public int PollOptionId { get; set; }

    /// <summary>The voter; <c>null</c> once their account was deleted (an anonymized vote).</summary>
    public int? UserId { get; set; }

    /// <summary>
    /// The poll's <c>BasePoll.AllowMultiple</c> when the vote was cast. Equal to the poll's current
    /// value by the composite FK, which also freezes the poll's value while this row exists.
    /// </summary>
    public bool AllowMultiple { get; set; }

    /// <summary>
    /// The single-choice guard, generated by the database (never set it): <see cref="PollId"/> on a
    /// single-choice poll, <c>null</c> on a multi-choice one. Unique with <see cref="UserId"/>, NULLS
    /// DISTINCT, so multi-choice rows and anonymized rows are untouched by it.
    /// </summary>
    public int? SingleChoicePollId { get; private set; }

    /// <summary>
    /// Only meaningful when the poll's <see cref="PollAnonymityMode"/> is <c>VoterChoice</c>:
    /// true = this voter opted to stay anonymous in the public voter list.
    /// </summary>
    public bool IsAnonymous { get; set; }

    // --- Navigation Properties ---
    public virtual PollOption PollOption { get; set; } = null!;
    public virtual User? User { get; set; }
}
